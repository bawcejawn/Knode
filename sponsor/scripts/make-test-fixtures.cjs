/**
 * Writes assembly/__tests__/fixtures.ts: test-only keys, addresses and signatures over fixed transaction ids.
 * Run from the sponsor folder with  npm run fixtures
 * The keys are derived from public labels; they are NOT secret and must never hold funds.
 */
const path = require("path");
const fs = require("fs");
const crypto = require("crypto");
const { Signer } = require("koilib");

const sha = (s) => crypto.createHash("sha256").update(s).digest();
const names = ["SELF", "USER", "OTHER"];
const signers = Object.fromEntries(names.map((n) => [n, new Signer({ privateKey: sha("knode-sponsor-test-" + n).toString("hex") })]));
const txIds = ["TX1", "TX2", "TX3"].map((t) => Buffer.concat([Buffer.from([0x12, 0x20]), sha("knode-sponsor-tx-" + t)]));
const hex = (b) => Buffer.from(b).toString("hex");
let out = "// Generated by scripts/make-test-fixtures.cjs. Test-only keys from public labels: never fund them.\n";
out += "export namespace F {\n";
for (const n of names) out += `  export const ${n} = "${signers[n].getAddress()}";\n`;
for (let t = 0; t < txIds.length; t++) out += `  export const TX${t + 1}_ID = "${hex(txIds[t])}";\n`;
(async () => {
  for (let t = 0; t < txIds.length; t++) {
    for (const n of names) {
      const sig = await signers[n].signHash(txIds[t].subarray(2));
      out += `  export const SIG_${n}_TX${t + 1} = "${hex(sig)}";\n`;
    }
  }
  out += "}\n";
  fs.writeFileSync(path.join(__dirname, "../assembly/__tests__/fixtures.ts"), out);
  console.log("wrote fixtures.ts");
})();
